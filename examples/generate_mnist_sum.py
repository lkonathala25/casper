from __future__ import annotations

import argparse
import sys
from pathlib import Path


def generate_mnist_sum_dsl(n_digits: int) -> str:
    """Signed-clause DSL for the MNIST-Sum constraint: S = y_1 + ... + y_N.

    Direct functional-link encoding: one clause per digit combination,

        [not d1]:y_1 or ... or [not dN]:y_N or [d1+...+dN]:S

    ("if the digits are (d1..dN) then S is their sum"). Declaration order is
    the network prob layout (digits then sum head); the ordering places the
    digits before S, so INFER assigns digit argmaxes freely and forces S to
    the singleton {sum of digits} — reproducing the hard-coded
    ConstraintLayer behaviour.

    Every resolvent of eliminating S is a tautology (two clauses with
    different sums differ on some digit, whose value-set union saturates), so
    the compiled artifact contains exactly the input clauses, bucketed at S.

    NOTE: the compile's minimal-conflict-pattern enumeration is exponential
    in S's domain size (9N+1), so this encoding is only compilable at N=2.
    Larger N stays on the hard-coded / from_function path.
    """
    n_sum = 9 * n_digits + 1
    digit_names = [f"y_{i + 1}" for i in range(n_digits)]

    lines: list[str] = [
        f"# MNIST-Sum N={n_digits}: S = " + " + ".join(digit_names),
        "# Generated by examples/generate_mnist_sum.py",
        "",
    ]
    for name in digit_names:
        lines.append(f"var {name} 10")
    lines.append(f"var S {n_sum}")
    lines.append("")
    lines.append("ordering " + " ".join(digit_names) + " S")
    lines.append("")

    def complement(v: int, domain: int) -> str:
        return ",".join(str(x) for x in range(domain) if x != v)

    combos: list[tuple[int, ...]] = [()]
    for _ in range(n_digits):
        combos = [c + (d,) for c in combos for d in range(10)]

    for combo in combos:
        parts = [
            f"[{complement(d, 10)}]:{name}"
            for d, name in zip(combo, digit_names)
        ]
        parts.append(f"[{sum(combo)}]:S")
        lines.append(" or ".join(parts))

    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(
        description="Generate the MNIST-Sum constraint DSL (S = sum of N digits)."
    )
    p.add_argument("n_digits", type=int)
    p.add_argument("out_path", type=Path)
    args = p.parse_args()

    if args.n_digits < 2:
        p.error("n_digits must be >= 2")
    if args.n_digits > 2:
        print(
            f"WARNING: N={args.n_digits} gives S a domain of "
            f"{9 * args.n_digits + 1}; the compile's pattern enumeration is "
            f"exponential in that domain and will not finish beyond N=2.",
            file=sys.stderr,
        )

    dsl = generate_mnist_sum_dsl(args.n_digits)
    args.out_path.write_text(dsl)
    n_clauses = sum(
        1 for line in dsl.splitlines()
        if line and not line.startswith(("var", "ordering", "#"))
    )
    print(f"Wrote {n_clauses} clauses to {args.out_path}")


if __name__ == "__main__":
    main()
