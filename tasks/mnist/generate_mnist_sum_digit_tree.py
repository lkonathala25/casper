from __future__ import annotations

import argparse
from pathlib import Path


def generate_mnist_sum_digit_tree_dsl(n_digits: int, network_first: bool = True) -> str:
    """Balanced decimal-adder tree for the sum of N digit variables.

    Every internal node uses ordinary right-to-left digit addition.  Digit
    domains remain 10 and carry domains remain 2 at every tree level.
    """
    if n_digits < 2 or n_digits & (n_digits - 1):
        raise ValueError("n_digits must be a power of two and >= 2")

    declarations: list[tuple[str, int]] = [
        (f"y_{i + 1}", 10) for i in range(n_digits)
    ]
    ordering = [name for name, _ in declarations]
    links: list[
        tuple[list[str], list[str], list[str], dict[int, str]]
    ] = []

    # Each value is represented by an MSB-first list of decimal digit names.
    current = [[f"y_{i + 1}"] for i in range(n_digits)]
    level = 1
    while len(current) > 1:
        next_level: list[list[str]] = []
        final_level = len(current) == 2
        for node in range(len(current) // 2):
            left = current[2 * node]
            right = current[2 * node + 1]
            width = len(left)
            prefix = "sum" if final_level else f"z_{level}_{node + 1}"
            output = [f"{prefix}_{i}" for i in range(width + 1)]
            carries = {
                i: f"c_{level}_{node + 1}_{i}" for i in range(1, width)
            }
            declarations.extend((name, 10) for name in output)
            declarations.extend((carries[i], 2) for i in sorted(carries, reverse=True))

            # Within one adder, inference follows its LSB-to-MSB carry chain.
            for i in range(width - 1, -1, -1):
                ordering.append(output[i + 1])
                ordering.append(carries[i] if i >= 1 else output[0])
            links.append((left, right, output, carries))
            next_level.append(output)
        current = next_level
        level += 1

    lines = [
        f"# Balanced decimal digit/carry sum tree for MNIST-Sum N={n_digits}.",
        "# Generated by examples/generate_mnist_sum_digit_tree.py",
        "",
    ]
    if network_first:
        # CompiledConstraintLayer requires the network's variables to be the
        # leading block, so declare the predicted ones (input digits y_*, answer
        # digits sum_*) before the tree's internal nodes z_* and carries c_*.
        # `ordering` resolves names, so the inference order is unaffected.
        predicted = [d for d in declarations
                     if d[0].startswith("y_") or d[0].startswith("sum_")]
        auxiliary = [d for d in declarations if d not in predicted]
        declarations = predicted + auxiliary
    lines.extend(f"var {name} {domain}" for name, domain in declarations)
    lines.extend(("", "ordering " + " ".join(ordering), ""))

    def complement(value: int, domain: int) -> str:
        return ",".join(str(x) for x in range(domain) if x != value)

    for left, right, output, carries in links:
        width = len(left)
        for i in range(width - 1, -1, -1):
            carry_in = carries.get(i + 1)
            carry_out = carries[i] if i >= 1 else output[0]
            lines.append(
                f"# ({left[i]}, {right[i]}"
                + (f", {carry_in}" if carry_in else "")
                + f") -> {output[i + 1]}, {carry_out}"
            )
            for a in range(10):
                for b in range(10):
                    for carry in range(2) if carry_in else (0,):
                        trigger = [
                            f"[{complement(a, 10)}]:{left[i]}",
                            f"[{complement(b, 10)}]:{right[i]}",
                        ]
                        if carry_in:
                            trigger.append(
                                f"[{complement(carry, 2)}]:{carry_in}"
                            )
                        total = a + b + carry
                        lines.append(
                            " or ".join(
                                trigger + [f"[{total % 10}]:{output[i + 1]}"]
                            )
                        )
                        lines.append(
                            " or ".join(
                                trigger + [f"[{total // 10}]:{carry_out}"]
                            )
                        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate a balanced decimal digit/carry MNIST-Sum tree."
    )
    parser.add_argument("n_digits", type=int)
    parser.add_argument("out_path", type=Path)
    args = parser.parse_args()
    try:
        dsl = generate_mnist_sum_digit_tree_dsl(args.n_digits)
    except ValueError as error:
        parser.error(str(error))
    args.out_path.write_text(dsl)
    clauses = sum(
        bool(line) and not line.startswith(("var", "ordering", "#"))
        for line in dsl.splitlines()
    )
    print(f"Wrote {clauses} clauses to {args.out_path}")


if __name__ == "__main__":
    main()
