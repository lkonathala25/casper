from __future__ import annotations

import argparse
from pathlib import Path


def generate_mnist_sum_tree_dsl(n_digits: int) -> str:
    """Balanced tree of categorical integer additions for MNIST-Sum.

    Leaves are the original domain-10 digit variables.  Every internal node
    stores the integer sum of its two children in one categorical variable.
    The construction currently requires a power-of-two number of leaves so
    every level is balanced.
    """
    if n_digits < 2 or n_digits & (n_digits - 1):
        raise ValueError("n_digits must be a power of two and >= 2")

    # A node is (name, domain).  Declaration and inference order are leaves,
    # then internal nodes from the bottom of the tree to the root.
    leaves = [(f"y_{i + 1}", 10) for i in range(n_digits)]
    levels: list[list[tuple[str, int]]] = [leaves]
    links: list[tuple[tuple[str, int], tuple[str, int], tuple[str, int]]] = []
    current = leaves
    level = 1
    while len(current) > 1:
        next_level = []
        for j in range(0, len(current), 2):
            left, right = current[j], current[j + 1]
            name = "S" if len(current) == 2 else f"p_{level}_{j // 2 + 1}"
            output = (name, left[1] + right[1] - 1)
            next_level.append(output)
            links.append((left, right, output))
        levels.append(next_level)
        current = next_level
        level += 1

    variables = [node for nodes in levels for node in nodes]
    lines = [
        f"# Balanced integer-sum tree for MNIST-Sum N={n_digits}.",
        "# Generated by examples/generate_mnist_sum_tree.py",
        "",
    ]
    lines.extend(f"var {name} {domain}" for name, domain in variables)
    lines.extend(("", "ordering " + " ".join(name for name, _ in variables), ""))

    def complement(value: int, domain: int) -> str:
        return ",".join(str(x) for x in range(domain) if x != value)

    for left, right, output in links:
        lines.append(
            f"# {output[0]} = {left[0]} + {right[0]}"
        )
        for left_value in range(left[1]):
            left_trigger = f"[{complement(left_value, left[1])}]:{left[0]}"
            for right_value in range(right[1]):
                right_trigger = (
                    f"[{complement(right_value, right[1])}]:{right[0]}"
                )
                lines.append(
                    f"{left_trigger} or {right_trigger} or "
                    f"[{left_value + right_value}]:{output[0]}"
                )

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate a balanced categorical integer-sum tree."
    )
    parser.add_argument("n_digits", type=int)
    parser.add_argument("out_path", type=Path)
    args = parser.parse_args()
    try:
        dsl = generate_mnist_sum_tree_dsl(args.n_digits)
    except ValueError as error:
        parser.error(str(error))
    args.out_path.write_text(dsl)
    clauses = sum(
        bool(line) and not line.startswith(("var", "ordering", "#"))
        for line in dsl.splitlines()
    )
    print(f"Wrote {clauses} clauses to {args.out_path}")


if __name__ == "__main__":
    main()
